class HelpTopic {
  final String id;
  final String title;
  final IconData icon;
  final HelpCategory category;

  /// جملة أو اتنين يفهّموا الموضوع ده ليه.
  final String summary;

  /// خطوات مرتّبة (الترقيم بيتحط في الواجهة).
  final List<String> steps;

  /// نصايح قصيرة بعد الخطوات.
  final List<String> tips;

  /// تحذير بارز (حاجة بتمسح بيانات مثلًا).
  final String? warning;

  /// كلمات بديلة للبحث (عامّية، مرادفات).
  final List<String> keywords;

  /// الشاشة اللي زرار "افتح الشاشة دي" بيودّي لها (اختياري).
  final String? route;
  final String? routeLabel;

  /// مواضيع مرتبطة (معرّفات).
  final List<String> related;

  const HelpTopic({
    required this.id,
    required this.title,
    required this.icon,
    required this.category,
    required this.summary,
    required this.steps,
    this.tips = const [],
    this.warning,
    this.keywords = const [],
    this.route,
    this.routeLabel,
    this.related = const [],
  });

  /// وقت القراءة التقريبي بالدقايق (≈ 150 كلمة في الدقيقة، دقيقة على الأقل).
  int get readMinutes {
    final text = [summary, ...steps, ...tips, if (warning != null) warning!]
        .join(' ')
        .replaceAll('**', '');
    final words = text.split(RegExp(r'\s+')).where((w) => w.isNotEmpty).length;
    final m = (words / 150).ceil();
    return m < 1 ? 1 : m;
  }
}

